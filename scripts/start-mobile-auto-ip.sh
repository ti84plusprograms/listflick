#!/usr/bin/env bash
# Update mobile/.env with the current LAN IP, then start Expo.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/mobile/.env"

IP=""
if ifconfig bridge100 >/dev/null 2>&1; then
  IP="$(ifconfig bridge100 | awk '/inet / {print $2}')"
fi

if [[ -z "$IP" ]]; then
  IP="$(
    ifconfig \
      | awk '
        /inet / && $2 != "127.0.0.1" && $2 !~ /^169\.254\./ {
          print $2
          exit
        }
      '
  )"
fi

if [[ -z "$IP" ]]; then
  echo "Could not detect a LAN IP address."
  echo "Connect to Wi-Fi or set mobile/.env manually."
  exit 1
fi

cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/start-mobile-auto-ip.sh
# Physical device (Custom Dev Client) - Mac LAN IP
EXPO_PUBLIC_API_URL=http://$IP:8000

# iOS Simulator / Android emulator only:
# EXPO_PUBLIC_API_URL=http://localhost:8000
EOF

echo "Set EXPO_PUBLIC_API_URL=http://$IP:8000"
export REACT_NATIVE_PACKAGER_HOSTNAME="$IP"
cd "$ROOT/mobile"
exec npx expo start --clear --offline
